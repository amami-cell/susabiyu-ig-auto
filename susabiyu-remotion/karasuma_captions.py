def story_for(name):
    d = clean(name)
    pool = _STORY_DEFAULT
    for keys, p in _STORY_POOLS:
        if any(k in d for k in keys):
            pool = p
            break
    h = sum(ord(c) for c in d) if d else 0
    return pool[h % len(pool)]


