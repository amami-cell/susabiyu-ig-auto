_POSTS_N = None


def _post_body(name, cap="", story=""):
    """SNS投稿の本文（元気お姉さんトーン・段落あり）。POSTS にあればそれ、無ければ
    cap/story から“それっぽい”本文を組み立てる（新メニューでも空にしない）。"""
    global _POSTS_N
    if _POSTS_N is None:
        _POSTS_N = {clean(k): v for k, v in POSTS.items()}
    raw = str(name or "")
    hit = POSTS.get(raw) or _POSTS_N.get(clean(raw))
    if hit:
        return hit
    d = clean(raw)
    lead = (story + "！") if story else ("本日のおすすめ、" + d + "です✨")
    mid = cap or (d + "、できたてをご用意しています")
    return "%s\n\n%s\n\nぜひ味わってくださいね🍷お待ちしてます！" % (lead, mid)


def caption_for(name):
    """戻り値 dict: title / story（ストーリー用の短句）/ cap（動画に焼く短い説明）/
    post（SNS投稿の本文・段落あり）/ tags。
    DISHES にあれば決定版、無ければカテゴリ・フォールバックで生成する。"""
    raw = str(name or "")
    d = clean(raw)
    hit = DISHES.get(raw) or DISHES.get(d)
    if hit:
        return {"title": d, "story": hit["story"], "cap": hit["cap"],
                "post": _post_body(raw, hit["cap"], hit["story"]),
                "tags": _uniq_tags(hit["tags"], BASE_TAGS)}
    for keys, story, fn, tags in CATS:
        if any(k in raw for k in keys):
            cap = fn(d)
            return {"title": d, "story": story, "cap": cap,
                    "post": _post_body(raw, cap, story),
                    "tags": _uniq_tags(tags, BASE_TAGS)}
    # 何にも当たらない新メニュー：中立で安全な既定。
    cap = "本日のおすすめ、%s。\nできたてを、ワインと一緒にどうぞ。" % d
    return {"title": d, "story": "本日の、おすすめ", "cap": cap,
            "post": _post_body(raw, cap, ""),
            "tags": _uniq_tags("#イタリアン #ワインに合う", BASE_TAGS)}


def story_for(name):
    """ストーリー動画に焼く“短い一言”だけを返す薄いヘルパー。"""
    return caption_for(name)["story"]


def post_caption(names, handle=""):
    """投稿本文（Instagramキャプション）を組み立てる。動画に映る料理名リスト(names)の
    先頭料理の“元気お姉さん本文(post)”＋店舗情報フッター(FOOTER)＋集約ハッシュタグを1本に。
    ※ユーザー要望により「本日のメニュー列挙」は廃止。フッターは一番下（タグの直前）に置く。"""
    names = [str(n).strip() for n in (names or []) if str(n).strip()]
    if not names:
        return ""
    lead = caption_for(names[0])
    body = lead.get("post") or lead.get("cap") or ""
    # タグ集約：各品の料理タグ → ブランドタグ → 集客タグ（POI）の順で重複除去、上限30本。
    tags = []
    for n in names:
        for t in caption_for(n)["tags"].split():
            if t and t not in tags:
                tags.append(t)
    for t in POI_TAGS.split():
        if t and t not in tags:
            tags.append(t)
    # 並び：本文 → 店舗情報フッター → ハッシュタグ（＝一番下に1箇所だけまとめる）。
    parts = [body, FOOTER, " ".join(tags[:30])]
    return "\n\n".join([p for p in parts if p])


