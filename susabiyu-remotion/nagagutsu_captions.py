def desc_for(name):
    """料理の“こだわり／説明書き”（動画の余白に添える用）。cap の締めの一行を使う。
    DESC_BREAKS に指定がある料理だけ、承認済みの位置に ｜（改行マーカー）を入れて返す。"""
