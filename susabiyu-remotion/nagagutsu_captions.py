def _uniq_tags(*groups):
    seen, out = set(), []
    for g in groups:
        for t in str(g or "").split():
            if t and t not in seen:
                seen.add(t)
                out.append(t)
    return " ".join(out)


def caption_for(name):
    """戻り値 dict: title / story（ストーリー用の短句）/ cap（投稿本文）/ tags。
    DISHES にあれば決定版、無ければカテゴリ・フォールバックで生成する。"""
    raw = str(name or "")
    d = clean(raw)
    hit = DISHES.get(raw) or DISHES.get(d)
    if hit:
        return {"title": d, "story": hit["story"], "cap": hit["cap"],
                "tags": _uniq_tags(hit["tags"], BASE_TAGS)}
    for keys, story, fn, tags in CATS:
        if any(k in raw for k in keys):
            return {"title": d, "story": story, "cap": fn(d), "tags": _uniq_tags(tags, BASE_TAGS)}
    # 何にも当たらない新メニュー：中立で安全な既定。
    return {"title": d, "story": "本日の、おすすめ",
            "cap": "本日のおすすめ、%s。\nできたてを、ワインと一緒にどうぞ。" % d,
            "tags": _uniq_tags("#イタリアン #ワインに合う", BASE_TAGS)}


def story_for(name):
    """ストーリー動画に焼く“短い一言”だけを返す薄いヘルパー。"""
    return caption_for(name)["story"]


def post_caption(names, handle=""):
    """投稿本文（Instagramキャプション）を組み立てる。動画に映る料理名リスト(names)から、
    先頭料理の本文＋（複数なら）本日のメニュー列挙＋集約ハッシュタグを1本の文字列に。
    ＝ぎふや同様「一発で全料理に、それっぽい投稿本文」が付く。"""
    names = [str(n).strip() for n in (names or []) if str(n).strip()]
    if not names:
        return ""
    lead = caption_for(names[0])
    # メニュー列挙（重複除去・順序維持・最大6品）
    titles = []
    for n in names:
        t = caption_for(n)["title"]
        if t and t not in titles:
            titles.append(t)
    # タグ集約（各品のタグ＋BASE、重複除去、上限15）
    tags = []
    for n in names:
        for t in caption_for(n)["tags"].split():
            if t and t not in tags:
                tags.append(t)
    parts = [lead["cap"]]
    if len(titles) > 1:
        parts.append("▼本日のメニュー\n" + "\n".join("・" + t for t in titles[:6]))
    if handle:
        parts.append(handle)
    parts.append(" ".join(tags[:15]))
    return "\n\n".join([p for p in parts if p])


