def story_for(name):
    """動画に焼き込む短い一言（料理ごとに決定論的に1本＝同じ料理なら毎回同じ）。"""
    d = clean(name)
    pools = _STORY_DEFAULT
    for keys, pool in _STORY_POOLS:
        if any(k in d for k in keys):
            pools = pool
            break
    h = sum(ord(c) for c in d) if d else 0
    return pools[h % len(pools)]


def _uniq_tags(*groups):
    seen, out = set(), []
    for g in groups:
        for t in str(g or "").split():
            if t and t not in seen:
                seen.add(t)
                out.append(t)
    return " ".join(out)


