# 料理ごとの「最終デザイン表」（tz_all＝最後に仕上げた版）。名前→{style, headline/sub, ...}。
# gifuya_design_table.json を正とし、毎日のDrive同期でもこの仕上げを維持する。
import os as _os
import json as _json
_DESIGN_TABLE = None


def _design_table():
    global _DESIGN_TABLE
    if _DESIGN_TABLE is None:
        try:
            with open(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)),
                                    "gifuya_design_table.json"), encoding="utf-8") as fp:
                _DESIGN_TABLE = _json.load(fp)
        except Exception:
            _DESIGN_TABLE = {}
    return _DESIGN_TABLE


def caption_for(name):
    """戻り値 dict: title/cap/tags/sub に加え、最終デザイン表があれば style/headline/pullback 等を付与。
    style="tanzaku"→短冊（headlineを焼く）／"vertical"→縦書き（subを説明文として焼く）。"""
    res = _caption_base(name)
    raw = str(name or "")
    cov = CAPTION_TABLE.get(raw)             # 料理ごとの本文・タグの磨き込み（cap/tagsのみ）
    if cov:
        res = dict(res)
        res.update(cov)
    ov = _design_table().get(raw)
    if ov:                                   # 画像内テキスト（style/headline/sub）は最終デザイン表を最優先
        res = dict(res)
        res.update(ov)
    else:                                    # 表に無い品は従来の部分一致フォールバック
        for keys, o2 in DESIGN_OVERRIDE:
            if any(k in raw for k in keys):
                res = dict(res)
                res.update(o2)
                break
    return res


def _caption_base(name):
    raw = str(name or "")
    d = clean(raw)
    for keys, cap, tags, sub in HERO:
        if any(k in raw for k in keys):
            return {"title": d, "cap": cap, "tags": tags, "sub": sub}
    if "串か" in raw:
        if "盛" in raw:
            return {"title": d, "cap": "迷ったらこれ、%s🍢\n人気の串をまとめて。シェアにもぴったり。" % d,
                    "tags": "#串かつ #串カツ #天神串かつ #天神居酒屋", "sub": "人気の串を一度に"}
        parts = re.split(r"[_＿ 　]", raw)
        top = clean("".join(parts[1:])) if len(parts) > 1 else d
        top = re.sub(r"[（(].*$", "", top).strip()          # 「(2本」等の付記を落とす
        top = re.sub(r"串かつ$", "", top).strip() or top     # 「本家牛串かつ」→「本家牛」
        cheese = any(k in top for k in ["チーズ", "モッツァレラ"])
        sea = any(k in top for k in ["海老", "イカ", "カキ", "キス", "サーモン", "たこ", "タコ", "穴子", "ほたて", "ホタテ"])
        meat = any(k in top for k in ["牛", "豚", "鶏", "ささみ", "ハムカツ", "ウインナー", "つくね"])
        if cheese:
            body = "とろ〜りチーズがのびる、%sの串かつ🍢\n熱々を軽い衣で包んで、ソースにくぐらせひと口。" % top
        elif sea:
            body = "魚介の旨みをぎゅっと、%sの串かつ🍢\nサクッと軽い衣で、ソースにくぐらせまずは一杯。" % top
        elif meat:
            body = "肉の旨みを衣に閉じ込めて、%sの串かつ🍢\nジューシーな一本を、ソースにくぐらせどうぞ。" % top
        else:
            body = "素材の甘みを引き立てる、%sの串かつ🍢\nサクッと軽い衣で、ソースにくぐらせひと口。" % top
        return {"title": d, "cap": body,
                "tags": "#串かつ #串カツ #天神串かつ #天神居酒屋", "sub": "サクッと軽い衣"}
    for keys, fn, tags, sub in CATS:
        if any(k in raw for k in keys):
            return {"title": d, "cap": fn(d), "tags": tags, "sub": sub}
    return {"title": d, "cap": "本日のおすすめ、%s。\nできたてをどうぞ。" % d,
            "tags": "#ぎふや #天神グルメ #大衆酒場", "sub": "本日のおすすめ"}


