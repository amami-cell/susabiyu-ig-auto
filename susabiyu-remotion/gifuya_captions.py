# 料理ごとの「デザイン様式」上書き。毎日のDrive同期でも維持される（sync が参照）。
#   style="tanzaku"→壁の短冊風（縦書き短冊＋旨ハンコ＋一言看板）。headline=白木看板の一言。
DESIGN_OVERRIDE = [
    (["厚揚げわさび", "厚揚げ　わさび", "厚揚げ わさび"], {"style": "tanzaku", "headline": "安くて、旨い。\nぎふやで乾杯。"}),
]


def caption_for(name):
    """戻り値 dict: title(整形名) / cap(本文) / tags(料理タグ) / sub(画像に焼くサブコピー)。
    料理名が DESIGN_OVERRIDE に該当すれば style/headline を上書きして付与する。"""
    res = _caption_base(name)
    raw = str(name or "")
    for keys, ov in DESIGN_OVERRIDE:
        if any(k in raw for k in keys):
            res = dict(res)
            res.update(ov)
            break
    return res


def _caption_base(name):
    raw = str(name or "")
    d = clean(raw)
    for keys, cap, tags, sub in HERO:
        if any(k in raw for k in keys):
            return {"title": d, "cap": cap, "tags": tags, "sub": sub}
    if "串か" in raw:
        if "盛" in raw:
            return {"title": d, "cap": "迷ったらこれ、%s🍢\n人気の串をまとめて。シェアにもぴったり。" % d,
                    "tags": "#串かつ #串カツ #天神串かつ", "sub": "人気の串を一度に"}
        parts = re.split(r"[_＿ 　]", raw)
        top = clean("".join(parts[1:])) if len(parts) > 1 else d
        return {"title": d, "cap": "サクッと軽い衣で、%sの串かつ🍢\nソースにくぐらせて、まずは一杯。" % top,
                "tags": "#串かつ #串カツ #天神串かつ", "sub": "サクッと軽い衣"}
    for keys, fn, tags, sub in CATS:
        if any(k in raw for k in keys):
            return {"title": d, "cap": fn(d), "tags": tags, "sub": sub}
    return {"title": d, "cap": "本日のおすすめ、%s。\nできたてをどうぞ。" % d,
            "tags": "#ぎふや #天神グルメ #大衆酒場", "sub": "本日のおすすめ"}


